# Version stamp for the pages that load the shared game files in src2/ (Kev, 16 Nov: "we need to avoid things like this",
# after a browser ran a new tabletop page on an old src2/lineup.js and dealt a robot that was dropped).
#
# What it does (run it after any change in src2/; tools/damage-lab/build.py runs it at the end):
#  1. fingerprints src2/*.js (their contents, so unchanged files keep the same fingerprint),
#  2. writes src2/version.js: window.ROBOCUS_FILES = { hash, date, robots, tuned },
#  3. puts ?b=<hash> on every ../src2/*.js link in the pages below, so a browser or GitHub Pages can never mix an
#     old cached file with a new page, and writes the expected hash into the page (<meta name="robocus-files">).
# The pages show the stamp in a corner and a red bar when the loaded files don't match (press Ctrl+F5).
#   python3 tools/stamp.py
import hashlib, pathlib, re, datetime, json
root = pathlib.Path(__file__).resolve().parent.parent
src2 = root / 'src2'
PAGES = ['prototypes/tabletop-2.html', 'prototypes/draft-arena.html', 'prototypes/sync-check.html', 'prototypes/flyoff-lab.html']
files = sorted(p for p in src2.glob('*.js') if p.name != 'version.js')
h = hashlib.sha1()
for p in files: h.update(p.name.encode()); h.update(p.read_bytes())
hash8 = h.hexdigest()[:8]
old = (src2 / 'version.js').read_text() if (src2 / 'version.js').exists() else ''
m = re.search(r'"date": "([^"]+)"', old)
date = m.group(1) if (m and f'"hash": "{hash8}"' in old) else datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
lu = (src2 / 'lineup.js').read_text()
rob = re.search(r"const ROBOTS = \{(.*?)\n  \};", lu, re.S); r4 = re.search(r"const ROBOTS4 = \{(.*?)\};", lu)
robots = len(re.findall(r"\b[A-Z]\w+: \[\d", rob.group(1))) + len(re.findall(r"\b[A-Z]\w+: \[\d", r4.group(1))) if rob and r4 else None
info = {'hash': hash8, 'date': date, 'robots': robots, 'tuned': 'const TUNED = true' in lu}
(src2 / 'version.js').write_text('// GENERATED by tools/stamp.py: which shared game files these are (the pages check it). Do not edit.\nwindow.ROBOCUS_FILES = ' + json.dumps(info) + ';\n')
CHECK = ('<script>/* tools/stamp.py: show which game files are loaded; a red bar when they don\'t match this page (old files in the browser\'s cache) */\n'
         '(function () { const want = (document.querySelector(\'meta[name="robocus-files"]\') || {}).content, F = window.ROBOCUS_FILES, ok = F && F.hash === want;\n'
         '  const s = document.createElement(\'div\'); s.id = \'robocusStamp\'; s.title = \'The game files this page runs on (tools/stamp.py)\';\n'
         '  s.style.cssText = \'position:fixed;left:6px;bottom:4px;z-index:99999;font:10px/1.2 ui-monospace,monospace;opacity:.55;pointer-events:none;color:#444;background:rgba(255,255,255,.6);padding:1px 4px;border-radius:3px\';\n'
         '  s.textContent = F ? \'files \' + F.hash + \' · \' + F.date + \' · \' + F.robots + \' robots\' : \'files: unknown\'; document.body.appendChild(s);\n'
         '  if (!ok) { const b = document.createElement(\'div\'); b.style.cssText = \'position:fixed;left:0;right:0;top:0;z-index:100000;background:#B23A2B;color:#fff;font:600 14px system-ui,sans-serif;padding:8px 12px;text-align:center\';\n'
         '    b.textContent = \'Old game files are loaded (\' + (F ? F.hash : \'none\') + \', this page wants \' + want + \'). Press Ctrl+F5, or close the tab and open the game again.\'; document.body.appendChild(b); }\n'
         '})();</script>\n')
for rel in PAGES:
    p = root / rel
    if not p.exists(): continue
    s = p.read_text()
    s = re.sub(r'src="\.\./src2/([\w-]+)\.js(\?b=[0-9a-f]*)?"', lambda m: f'src="../src2/{m.group(1)}.js?b={hash8}"', s)
    if '../src2/version.js' not in s:   # load it first among the shared files
        s = re.sub(r'(<script src="\.\./src2/)', f'<script src="../src2/version.js?b={hash8}"></script>\n\\1', s, count=1)
    if 'name="robocus-files"' in s: s = re.sub(r'<meta name="robocus-files" content="[0-9a-f]*">', f'<meta name="robocus-files" content="{hash8}">', s)
    else: s = s.replace('<meta charset="utf-8">', f'<meta charset="utf-8"><meta name="robocus-files" content="{hash8}">', 1)
    if 'id = \'robocusStamp\'' not in s:
        i = s.rfind('</body>'); s = (s[:i] + CHECK + s[i:]) if i >= 0 else s + CHECK
    p.write_text(s)
print(f'stamp {hash8} ({date}, {robots} robots{", tuned" if info["tuned"] else ""}) on', ', '.join(r for r in PAGES if (root / r).exists()))
